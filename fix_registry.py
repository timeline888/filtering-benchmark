#!/usr/bin/env python3
import os

base = os.path.join('e:' + os.sep, 'Qoder项目', '滤波基石系统设计', 'filtering_benchmark', 'src', 'algorithms')
path = os.path.join(base, 'registry.py')

# Build content line by line - NO f-strings, NO escaped quotes in strings
lines = []

def a(s):
    lines.append(s)

a('# -*- coding: utf-8 -*-')
a('')
a('import importlib')
a('import os as _os')
a('')
a('from loguru import logger')
a('from ..core.exceptions import AlgorithmNotFoundError')
a('')
a('')
a('class AlgorithmMeta:')
a('    def __init__(self, algorithm_id, algorithm_class):')
a('        self.algorithm_id = algorithm_id')
a('        self.algorithm_class = algorithm_class')
a('        self.name = algorithm_class.name')
a('        self.category = algorithm_class.category')
a('        self.complexity = algorithm_class.complexity')
a('        self.tags = algorithm_class.tags')
a('        self.requires_gpu = algorithm_class.requires_gpu')
a('        self.default_params = algorithm_class.default_params')
a('')
a('')
a('class AlgorithmRegistry:')
a('    _instance = None')
a('    _initialized = False')
a('')
a('    def __new__(cls):')
a('        if cls._instance is None:')
a('            cls._instance = super().__new__(cls)')
a('        return cls._instance')
a('')
a('    def __init__(self):')
a('        if self._initialized:')
a('            return')
a('        self._initialized = True')
a('        self._registry = {}')
a('        self._discovered = False')
a('')
a('    def register(self, algorithm_id, algorithm_class):')
a("        dbg_msg = 'Registered: ' + algorithm_class.name")
a('        logger.debug(dbg_msg)')
a('        self._registry[algorithm_id] = AlgorithmMeta(algorithm_id, algorithm_class)')
a('')
a('    def get(self, algorithm_id):')
a('        self.ensure_discovered()')
a('        if algorithm_id not in self._registry:')
a('            raise AlgorithmNotFoundError(algorithm_id)')
a('        return self._registry[algorithm_id]')
a('')
a('    def create_instance(self, algorithm_id, **params):')
a('        meta = self.get(algorithm_id)')
a('        return meta.algorithm_class(**params)')
a('')
a('    def list_ids(self):')
a('        self.ensure_discovered()')
a('        return list(self._registry.keys())')
a('')
a('    def list_algorithms(self):')
a('        self.ensure_discovered()')
a('        return list(self._registry.values())')
a('')
a('    def filter(self, category=None, complexity=None, tags=None, requires_gpu=None):')
a('        results = self.list_algorithms()')
a('        if category:')
a('            results = [m for m in results if m.category == category]')
a('        if complexity:')
a('            results = [m for m in results if m.complexity == complexity]')
a('        if tags:')
a('            results = [m for m in results if any(t in m.tags for t in tags)]')
a('        if requires_gpu is not None:')
a('            results = [m for m in results if m.requires_gpu == requires_gpu]')
a('        return results')
a('')
a('    def count(self):')
a('        return len(self._registry)')
a('')
a('    def ensure_discovered(self):')
a('        if self._discovered:')
a('            return')
a('        self._discover_algorithms()')
a('        self._discovered = True')
a("        logger.info('Auto-discovery: ' + str(self.count()) + ' algorithms')")
a('')
a('    def _discover_algorithms(self):')
a('        cd = _os.path.dirname(_os.path.abspath(__file__))')
a('        mods = []')
a('        for item in sorted(_os.listdir(cd)):')
a('            ip = _os.path.join(cd, item)')
a('            if item.endswith(\".py\") and not item.startswith(\"_\"):')
a('                mods.append(item[:-3])')
a('            elif _os.path.isdir(ip) and not item.startswith(\"_\"):')
a('                initf = _os.path.join(ip, \"__init__.py\")')
a('                if _os.path.exists(initf):')
a('                    for sub in sorted(_os.listdir(ip)):')
a('                        if sub.endswith(\".py\") and not sub.startswith(\"_\"):')
a('                            mods.append(item + \".\" + sub[:-3])')
a('')
a('        for mn in mods:')
a('            ok = False')
a("            for pr in ['src.algorithms', 'algorithms']:")
a('                try:')
a('                    importlib.import_module(pr + \".\" + mn)')
a('                    ok = True')
a('                    break')
a('                except Exception:')
a('                    continue')
a('            if not ok:')
a('                try:')
a('                    importlib.import_module(mn)')
a('                except Exception:')
a('                    pass')
a('')
a('registry = AlgorithmRegistry()')

content = '\n'.join(lines)

with open(path, 'w', encoding='utf-8') as f:
    f.write(content)

print('Written', os.path.getsize(path), 'bytes to', path)
